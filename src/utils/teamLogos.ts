  // 2. Try normalizing team name (remove SC, FC, Al, Club, CF, etc.)
  const cleaned = nameTrimmed
    .replace(/^(FC|CF|SC|RC|RCD|AJ|AS|OGC|CA|نادي|فريق)\s+/i, '')
    .replace(/\s+(FC|CF|SC|UD|SCO|OSC|Balompié|de Barcelona|إف سي|اف سي)$/i, '')
